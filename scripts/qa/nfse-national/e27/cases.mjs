/** Structural XML vectors; never evidence of fiscal issuance.
 * @param {typeof import('../../../../src/lib/nfse/xml-nacional/xml-tree').XML_LIMITS} limits
 */
export function securityCases(limits) {
  const declaration = '<?xml version="1.0" encoding="UTF-8"?>'
  /** @type {{id: string, family: string, xml: string, accepted: boolean, code?: string, text?: string, attribute?: string}[]} */
  const cases = []
  /** @param {string} id @param {string} family @param {string} xml @param {boolean} accepted @param {{code?: string, text?: string, attribute?: string}} [extra] */
  const add = (id, family, xml, accepted, extra = {}) => cases.push({ id, family, xml, accepted, ...extra })
  add('atributo-identico', 'attributes', '<a v="1" v="1"/>', false)
  add('atributo-conflitante', 'attributes', '<a v="1" v="2"/>', false)
  add('atributo-expandido', 'attributes', '<a xmlns:x="urn:u" xmlns:y="urn:u" x:v="1" y:v="2"/>', false)
  add('xmlns-duplicado', 'attributes', '<a xmlns="urn:a" xmlns="urn:b"/>', false)
  add('atributos-distintos', 'attributes', '<a x="001" y="0"/>', true, { attribute: '001' })
  add('namespace-default-atributo-sem-uri', 'attributes', '<a xmlns="urn:u" x="001"/>', true, { attribute: '001' })
  add('mesmo-local-uris-distintas', 'attributes', '<a xmlns:x="urn:a" xmlns:y="urn:b" x:v="1" y:v="2"/>', true)
  add('atributo-local-e-prefixado', 'attributes', '<a xmlns:x="urn:a" v="1" x:v="2"/>', true)
  add('atributo-delimitadores-em-valor', 'attributes', '<a x="> / = &quot;" y="é"/>', true, { attribute: '> / = "' })
  add('binding-declarado-apos-uso', 'namespace', '<x:a x:v="1" xmlns:x="urn:u"/>', true)
  add('prefixo-sem-binding', 'namespace', '<x:a/>', false)
  add('atributo-prefixo-sem-binding', 'namespace', '<a x:v="1"/>', false)
  add('xml-binding-indevido', 'namespace', '<a xmlns:xml="urn:evil"/>', false)
  add('prefixo-xmlns-indevido', 'namespace', '<a xmlns:xmlns="urn:evil"/>', false)
  for (const [suffix, xml] of Object.entries({ text: '<a>\u0001</a>', attribute: '<a x="\u0001"/>',
    comment: '<a><!--\u0001--></a>', cdata: '<a><![CDATA[\u0001]]></a>' })) add(`controle-${suffix}`, 'characters', xml, false)
  add('surrogate-alto-isolado', 'characters', '<a>\ud800</a>', false)
  add('surrogate-baixo-isolado', 'characters', '<a>\udc00</a>', false)
  add('nulo-literal', 'characters', '<a>\u0000</a>', false)
  add('fffe-literal', 'characters', '<a>\ufffe</a>', false)
  add('unicode-suplementar-acentos', 'characters', '<a>Áção 😀</a>', true, { text: 'Áção 😀' })
  add('whitespace-xml-permitido', 'characters', '<a>\t\n </a>', true, { text: '\t\n ' })
  add('entidades-xml', 'entities', '<a>&amp;&lt;&gt;&apos;&quot;</a>', true, { text: '&<>\'"' })
  add('referencias-validas', 'entities', '<a>&#65;&#xE9;&#x1F600;&#9;</a>', true, { text: 'Aé😀\t' })
  add('referencia-atributo', 'entities', '<a x="&#48;&#48;&#49;"/>', true, { attribute: '001' })
  for (const [suffix, token] of Object.entries({ zero: '&#0;', control: '&#x1;', surrogate: '&#xD800;',
    overflow: '&#x110000;', bad_decimal: '&#12junk;', bad_hex: '&#xZZ;', fffe: '&#xFFFE;' })) {
    add(`referencia-invalida-${suffix}`, 'entities', `<a>${token}</a>`, false)
  }
  add('entidade-desconhecida', 'entities', '<a>&unknown;</a>', false)
  add('entidade-html', 'entities', '<a>&copy;</a>', false)
  add('entidade-xml-case-sensitive', 'entities', '<a>&AMP;</a>', false)
  add('referencia-literal-cdata', 'entities', '<a><![CDATA[&#0;&unknown;]]></a>', true, { text: '&#0;&unknown;' })
  add('declaracao-unica', 'declaration', declaration + '<a/>', true)
  add('declaracao-sem-encoding', 'declaration', '<?xml version="1.0"?><a/>', true)
  add('declaracao-standalone', 'declaration', '<?xml version="1.0" standalone="yes"?><a/>', true)
  add('declaracao-espacos-xml', 'declaration', '<?xml\tversion = \'1.0\'\nencoding="utf-8" standalone="no" ?><a/>', true)
  add('sem-declaracao', 'declaration', '<a/>', true)
  add('bom-valido', 'bom', '\ufeff' + declaration + '<a/>', true)
  add('bom-duplo', 'bom', '\ufeff\ufeff' + declaration + '<a/>', false)
  add('bom-deslocado', 'bom', ' \ufeff' + declaration + '<a/>', false)
  add('bom-utf8-mojibake', 'bom', 'ï»¿' + declaration + '<a/>', false)
  add('bom-reverso-proibido', 'bom', '\ufffe' + declaration + '<a/>', false)
  add('declaracao-duplicada', 'declaration', declaration + declaration + '<a/>', false)
  add('declaracao-apos-espaco', 'declaration', ' ' + declaration + '<a/>', false)
  add('declaracao-apos-comentario', 'declaration', '<!--x-->' + declaration + '<a/>', false)
  add('declaracao-dentro-raiz', 'declaration', '<a>' + declaration + '</a>', false)
  add('declaracao-apos-raiz', 'declaration', '<a/>' + declaration, false)
  add('declaracao-case-indevido', 'declaration', '<?XML version="1.0"?><a/>', false)
  add('declaracao-sem-versao', 'declaration', '<?xml encoding="UTF-8"?><a/>', false)
  add('declaracao-versao-duplicada', 'declaration', '<?xml version="1.0" version="1.0"?><a/>', false)
  add('declaracao-ordem-indevida', 'declaration', '<?xml encoding="UTF-8" version="1.0"?><a/>', false)
  add('declaracao-atributo-extra', 'declaration', '<?xml version="1.0" extra="x"?><a/>', false)
  add('declaracao-standalone-invalido', 'declaration', '<?xml version="1.0" standalone="true"?><a/>', false)
  add('declaracao-versao-nao-suportada', 'declaration', '<?xml version="1.1"?><a/>', false)
  add('declaracao-encoding-nao-suportado', 'declaration', '<?xml version="1.0" encoding="ISO-8859-1"?><a/>', false)
  add('declaracao-whitespace-nao-xml', 'declaration', '<?xml\u00a0version="1.0"?><a/>', false)
  add('xml-stylesheet', 'declaration', declaration + '<?xml-stylesheet href="a"?><a/>', true)
  add('declaracao-texto-cdata', 'declaration', '<a><![CDATA[<?xml version="1.0"?>]]></a>', true, { text: '<?xml version="1.0"?>' })
  add('declaracao-texto-comentario', 'declaration', '<a><!--<?xml version="1.0"?>--></a>', true)
  add('xml-truncado', 'malformed', '<a><b>', false)
  add('xml-fechamento-errado', 'malformed', '<a><b></a>', false)
  add('xml-multiplas-raizes', 'malformed', '<a/><b/>', false)
  add('texto-fora-raiz', 'malformed', 'unexpected<a/>', false)
  add('nome-invalido', 'malformed', '<1a/>', false)
  add('xml-sem-atributo-aspas', 'malformed', '<a x=1/>', false)
  add('xml-comentario-invalido', 'malformed', '<a><!--a--b--></a>', false)
  add('dtd-arquivo', 'dtd', '<!DOCTYPE a [<!ENTITY x SYSTEM "file:///not-authorized">]><a>&x;</a>', false, { code: 'XML_DTD_FORBIDDEN' })
  add('dtd-rede', 'dtd', '<!DOCTYPE a SYSTEM "https://invalid.example/xxe"><a/>', false, { code: 'XML_DTD_FORBIDDEN' })
  add('dtd-expansao', 'dtd', '<!DOCTYPE a [<!ENTITY a "x"><!ENTITY b "&a;&a;">]><a>&b;</a>', false, { code: 'XML_DTD_FORBIDDEN' })
  add('profundidade-limite', 'limits', '<a>'.repeat(limits.depth) + '</a>'.repeat(limits.depth), true)
  add('profundidade-excedida', 'limits', '<a>'.repeat(limits.depth + 1) + '</a>'.repeat(limits.depth + 1), false, { code: 'XML_LIMIT' })
  add('nos-limite', 'limits', '<a>' + '<b/>'.repeat(limits.nodes - 1) + '</a>', true)
  add('nos-excedidos', 'limits', '<a>' + '<b/>'.repeat(limits.nodes) + '</a>', false, { code: 'XML_LIMIT' })
  /** @param {number} count */
  const attributeXml = count => '<a ' + Array.from({ length: count }, (_, i) => `x${i}="1"`).join(' ') + '/>'
  add('atributos-limite', 'limits', attributeXml(limits.attributes), true)
  add('atributos-excedidos', 'limits', attributeXml(limits.attributes + 1), false, { code: 'XML_LIMIT' })
  add('atributos-brutos-repetidos', 'limits', '<a ' + 'v="1" '.repeat(limits.attributes + 1) + '/>', false)
  add('bytes-limite', 'limits', '<a>' + 'x'.repeat(limits.bytes - 7) + '</a>', true)
  add('bytes-excedidos', 'limits', '<a>' + 'x'.repeat(limits.bytes - 6) + '</a>', false, { code: 'XML_SIZE' })
  return cases
}
